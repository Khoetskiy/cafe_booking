from enum import StrEnum

from app.core.constants import ROLE_ADMIN, ROLE_MANAGER, ROLE_USER


class UserRole(StrEnum):
    """Роли пользователей в системе.

    Определяют уровень доступа пользователя и его возможности
    при работе с системой бронирования.

    Роли:
        ADMIN:
            Администратор системы.
            Имеет полный доступ ко всем данным и операциям:
            - управление пользователями;
            - управление кафе и их настройками;
            - управление слотами и столами;
            - управление всеми бронированиями;
            - доступ к административным действиям (активация/деактивация и др.).

        MANAGER:
            Менеджер кафе.
            Имеет доступ только к данным своего кафе:
            - управление бронированиями своего кафе (подтверждение, отмена, завершение);
            - управление столами и слотами;
            - ограниченный доступ к операциям без глобальных прав.

        USER:
            Обычный пользователь (клиент).
            Может:
            - создавать бронирования;
            - просматривать свои бронирования;
            - отменять собственные бронирования;
            - получать доступ к открытой информации о кафе/столы/слоты.
    """

    ADMIN = ROLE_ADMIN
    MANAGER = ROLE_MANAGER
    USER = ROLE_USER


class BookingStatus(StrEnum):
    """Статусы бронирования.

    Определяют текущее состояние бронирования в системе и его жизненный цикл.

    Статусы:
        PENDING:
            Бронирование создано, но ещё не подтверждено.
            Ожидает подтверждения со стороны администратора или менеджера кафе.

        CONFIRMED:
            Бронирование подтверждено администратором или менеджером.
            Ожидается визит клиента в указанное время.

        CANCELLED:
            Бронирование отменено.
            Может быть отменено:
            - пользователем (если передумал);
            - администратором или менеджером.

        COMPLETED:
            Бронирование успешно завершено.
            Клиент пришёл, и бронирование было обслужено.

    Допустимые переходы статусов:
        PENDING → CONFIRMED
        PENDING → CANCELLED
        CONFIRMED → CANCELLED
        CONFIRMED → COMPLETED

    Ограничения:
        - Нельзя подтвердить бронирование, если оно не в статусе PENDING.
        - Нельзя завершить бронирование, если оно не в статусе CONFIRMED.
        - Нельзя изменить статус после перехода в COMPLETED.
        - Отмена возможна только из статусов PENDING и CONFIRMED.

    Примечание:
        Статус бронирования не связан с полем `is_active`.
        `is_active` отвечает за техническую активность,
        а статус — за бизнес-состояние бронирования.
    """

    PENDING = 'pending'
    CONFIRMED = 'confirmed'
    CANCELLED = 'cancelled'
    COMPLETED = 'completed'
